/* small SVG line chart */
function lineChart(series, opts){
  opts=opts||{}; var W=opts.w||560, H=opts.h||200, pl=36, pr=12, pt=10, pb=opts.labels?34:12;
  var n = Math.max.apply(null, series.map(function(s){return s.values.length;}));
  function X(i){ return n<=1?pl+(W-pl-pr)/2:pl+i*(W-pl-pr)/(n-1); }
  function Y(v){ return pt+(1-v)*(H-pt-pb); }
  var g='';
  [0,.25,.5,.75,1].forEach(function(t){ g+='<line class="gridl" x1="'+pl+'" x2="'+(W-pr)+'" y1="'+Y(t)+'" y2="'+Y(t)+'"/><text x="'+(pl-8)+'" y="'+(Y(t)+4)+'" text-anchor="end">'+Math.round(t*100)+'%</text>'; });
  if(opts.labels) opts.labels.forEach(function(l,i){ if(n>10 && i%2 && i!==n-1) return; g+='<text x="'+X(i)+'" y="'+(H-8)+'" text-anchor="middle">'+esc(l)+'</text>'; });
  series.forEach(function(s){
    var pts=[]; s.values.forEach(function(v,i){ if(v!=null) pts.push([X(i),Y(v),v,i]); });
    if(pts.length>1) g+='<path d="M'+pts.map(function(p){return p[0].toFixed(1)+","+p[1].toFixed(1);}).join(" L")+'" fill="none" stroke="'+s.color+'" stroke-width="'+(s.w||2)+'" stroke-linejoin="round" stroke-linecap="round"/>';
    pts.forEach(function(p){ g+='<circle cx="'+p[0]+'" cy="'+p[1]+'" r="3" fill="'+s.color+'"><title>'+esc(s.name+": "+Math.round(p[2]*100)+"%"+(opts.labels?" ("+opts.labels[p[3]]+")":""))+'</title></circle>'; });
  });
  return '<svg viewBox="0 0 '+W+' '+H+'" role="img" aria-label="'+esc(opts.aria||"line chart")+'">'+g+'</svg>';
}
