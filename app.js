function priceFloors(p){
  if(!p) return {wedding:null, session:null};
  var wedding=null, hourly=false, m = /wedding[^$;]*?\$([\d,]+)(\/hr)?/i.exec(p);
  if(m){ if(m[2]) hourly=true; else wedding=+m[1].replace(/,/g,""); }
  var re=/\$([\d,]+)/g, x, big=[], small=[];
  while((x=re.exec(p))){
    var v=+x[1].replace(/,/g,""), before=p.slice(Math.max(0,x.index-18),x.index).toLowerCase(), after=p.slice(x.index+x[0].length,x.index+x[0].length+10).toLowerCase();
    if(/deposit/.test(after) || /sports/.test(before) || /^\/(hr|event)/.test(after)) continue;
    (v>=1000?big:small).push(v);
  }
  if(wedding==null && !hourly && big.length) wedding=Math.min.apply(null,big);
  return {wedding:wedding, session: small.length?Math.min.apply(null,small):null, hourly:hourly};
}

