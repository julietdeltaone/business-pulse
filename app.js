function followChart(hist){
  var W=440,H=90,v=hist.map(function(x){return x.count;}), lo=Math.min.apply(null,v), hi=Math.max.apply(null,v); if(hi===lo){ hi+=5; lo-=5; }
  var pts=hist.map(function(x,i){ return [20+i*(W-40)/(hist.length-1), 12+(1-(x.count-lo)/(hi-lo))*(H-36)]; });
  return '<svg viewBox="0 0 '+W+' '+H+'"><path d="M'+pts.map(function(p){return p[0]+","+p[1];}).join(" L")+'" stroke="#DCE0E8" stroke-width="2" fill="none"/>'+
    pts.map(function(p,i){ return '<circle cx="'+p[0]+'" cy="'+p[1]+'" r="3" fill="#DCE0E8"/><text x="'+p[0]+'" y="'+(H-4)+'" text-anchor="middle">'+shortDate(hist[i].date)+'</text><text x="'+p[0]+'" y="'+(p[1]-7)+'" text-anchor="middle" fill="#AAB1BF">'+fmt(hist[i].count)+'</text>'; }).join("")+'</svg>';
}

